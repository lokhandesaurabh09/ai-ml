a = 17
b = 5

# Arithmatic
print("Add:", a + b)
print("Subtract:", a - b)
print("Multiply:", a * b)
print("Divide:", a / b)            #3.4(always float)
print("Floor Divide:", a // b)     #3(drops decimals)
print("Remainder:", a % b)
print("Power:", a ** 2)

# Comparison

print(a == b)
print(a != b)
print(a > b)
print(a <= b)

# Logical

print(a > 10 and b > 10) 
print(a > 10 or b > 10)
print(not (a > b))

#Assignment

x = 10
x += 5
x *= 2
print("x:", x)